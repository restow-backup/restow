#!/usr/bin/env node
/**
 * The "no auto-activation" test of the recovery ISO (docs/BAREMETAL.md 21.2, risk table 20:
 * an old disk stays attached): the ISO is booted in QEMU/KVM with a second disk that carries
 * an md RAID1, a volume group on it with an ext4 LV, and a swap partition, and
 * integrations/recovery/test/no-autoactivation.sh runs inside the started ISO. Nothing of the
 * disk may be active; the run fails on FAIL.
 *
 *   node scripts/recovery-e2e/no-autoactivation.mjs --iso <iso> [--work-dir DIR]
 *
 * Two boots of the ISO's own live system (direct kernel boot, like the machine factory of
 * run.mjs): the first prepares the disk with the ISO's mdadm, sfdisk and LVM and stops
 * everything again; the second is a normal start (restow-recover.service runs) and runs the
 * check from a read-only ISO 9660 carrier, so the carrier itself is no mounted disk file
 * system. Needs KVM, qemu-system-x86_64, qemu-img and xorriso.
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assertKvm, createDisk, startMachine, waitForSerial } from "./lib/qemu.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const CHECK = join(repoRoot, "integrations/recovery/test/no-autoactivation.sh");

/** The serial number of the prepared disk; the ISO finds it as /dev/disk/by-id/virtio-<serial>. */
export const DISK_SERIAL = "restow-na-disk0";
export const CARRIER_LABEL = "RESTOWCHECK";

/** The kernel command line of a boot: `prepare` without the recovery program, `check` with it. */
export function cmdline(mode) {
  if (mode !== "prepare" && mode !== "check") throw new Error(`unknown mode ${mode}`);
  return [
    "boot=live",
    "components",
    "noswap",
    "nopersistence",
    "console=ttyS0,115200n8",
    // The check boots like the ISO does; only the preparation keeps the program away.
    ...(mode === "prepare" ? ["systemd.mask=restow-recover.service"] : []),
    `systemd.run="/usr/bin/sh -c 'mkdir -p /run/restow-check && mount -o ro /dev/disk/by-label/${CARRIER_LABEL} /run/restow-check && exec sh /run/restow-check/run.sh ${mode}'"`,
    "systemd.run_success_action=poweroff",
    "systemd.run_failure_action=poweroff",
  ].join(" ");
}

/** run.sh on the carrier: prepares the disk or runs the check, all output on the serial console. */
export function runScript() {
  return `#!/bin/sh
# Generated by scripts/recovery-e2e/no-autoactivation.mjs.
exec >/dev/ttyS0 2>&1
mode="$1"
disk=/dev/disk/by-id/virtio-${DISK_SERIAL}
udevadm settle --timeout=120 || true
if [ "$mode" = prepare ]; then
  set -eux
  sfdisk --wipe always "$disk" <<'EOF'
label: gpt
size=256MiB, type=A19D880F-05FC-4D3B-A006-743F0F84911E
size=256MiB, type=A19D880F-05FC-4D3B-A006-743F0F84911E
size=128MiB, type=0657FD6D-A4AB-43C4-84E5-0933C84B4F4F
EOF
  udevadm settle --timeout=60
  mdadm --create /dev/md/naauto --run --level=1 --raid-devices=2 --metadata=1.2 --assume-clean \\
    "$disk-part1" "$disk-part2"
  udevadm settle --timeout=60
  md=$(readlink -f /dev/md/naauto)
  pvcreate --devices "$md" -ff -y "$md"
  vgcreate --devices "$md" naauto "$md"
  lvcreate --devices "$md" -y -n data -L 64m naauto
  udevadm settle --timeout=60
  mkfs.ext4 -q -F /dev/mapper/naauto-data
  mkswap "$disk-part3"
  vgchange --devices "$md" -an naauto
  mdadm --stop "$md"
  sync
  echo NO-AUTOACTIVATION-PREPARED
  exit 0
fi
# The check: what the started ISO did by itself, after udev and a moment for late units.
sleep 15
lsblk -o NAME,TYPE,FSTYPE,MOUNTPOINTS "$disk" || true
sh /run/restow-check/no-autoactivation.sh
echo "NO-AUTOACTIVATION-RESULT $?"
`;
}

/** The result of the check in a serial log: 0 (nothing active), 1 (something was), or null. */
export function resultOf(serial) {
  const match = /NO-AUTOACTIVATION-RESULT (\d+)/.exec(serial);
  return match ? Number(match[1]) : null;
}

function sh(command, args) {
  execFileSync(command, args, { stdio: ["ignore", "inherit", "inherit"] });
}

export function parseArgs(argv) {
  const options = { workDir: "no-autoactivation-out" };
  for (let index = 0; index < argv.length; index++) {
    const flag = argv[index];
    const next = argv[index + 1];
    if (
      (flag === "--iso" || flag === "--work-dir") &&
      (next === undefined || next.startsWith("--"))
    )
      throw new Error(`${flag} needs a value`);
    if (flag === "--iso") options.iso = argv[++index];
    else if (flag === "--work-dir") options.workDir = argv[++index];
    else throw new Error(`unknown option ${flag}`);
  }
  if (!options.iso) throw new Error("--iso <file> is needed");
  return options;
}

async function boot(options, mode, kernel, initrd, disk, carrier) {
  const serialLog = join(options.workDir, `${mode}.log`);
  const machine = startMachine({
    name: `no-autoactivation-${mode}`,
    firmware: "bios",
    memoryMiB: 2048,
    disks: [disk],
    cdrom: options.iso,
    extraDisks: [carrier],
    serialLog,
    qmpSocket: join(options.workDir, `${mode}.qmp`),
    kernel: { file: kernel, initrd, append: cmdline(mode) },
  });
  const pattern =
    mode === "prepare" ? /NO-AUTOACTIVATION-PREPARED/ : /NO-AUTOACTIVATION-RESULT \d+/;
  try {
    await waitForSerial(serialLog, pattern, { timeoutMs: 15 * 60_000, intervalMs: 1000, machine });
  } finally {
    // The run unit powers the machine off; a hung boot is stopped after the wait.
    const timer = setTimeout(() => machine.child.kill("SIGKILL"), 120_000);
    await machine.exited;
    clearTimeout(timer);
  }
  return readFileSync(serialLog, "utf8");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  assertKvm();
  options.workDir = resolve(options.workDir);
  options.iso = resolve(options.iso);
  mkdirSync(options.workDir, { recursive: true });
  const kernel = join(options.workDir, "vmlinuz");
  const initrd = join(options.workDir, "initrd.img");
  for (const [from, to] of [
    ["/live/vmlinuz", kernel],
    ["/live/initrd.img", initrd],
  ]) {
    sh("xorriso", ["-osirrox", "on", "-indev", options.iso, "-extract", from, to]);
  }
  const tree = join(options.workDir, "carrier");
  mkdirSync(tree, { recursive: true });
  writeFileSync(join(tree, "run.sh"), runScript());
  copyFileSync(CHECK, join(tree, "no-autoactivation.sh"));
  const carrier = join(options.workDir, "carrier.iso");
  sh("xorriso", ["-as", "mkisofs", "-quiet", "-R", "-V", CARRIER_LABEL, "-o", carrier, tree]);
  const disk = { serial: DISK_SERIAL, bus: "virtio", file: join(options.workDir, "old.qcow2") };
  await createDisk((command, args) => sh(command, args), disk.file, "1G");
  await boot(options, "prepare", kernel, initrd, disk, carrier);
  const serial = await boot(options, "check", kernel, initrd, disk, carrier);
  const result = resultOf(serial);
  if (result !== 0) {
    const lines = serial.split("\n");
    const from = lines.findIndex((line) => line.includes("FAIL:"));
    console.error(lines.slice(Math.max(0, from - 5)).join("\n"));
    throw new Error(`no-autoactivation: something of the old disk was active (result ${result})`);
  }
  console.log("no-autoactivation: the md array, the volume group and the swap stayed inactive");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
