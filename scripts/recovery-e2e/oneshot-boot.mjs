#!/usr/bin/env node
import { execFileSync } from "node:child_process";
/**
 * "Start without medium" (docs/BAREMETAL-ONESHOT.md 4.2, 19.2): the recovery ISO's live system
 * started the way a oneshot restore starts it with kexec, from the kernel, the ISO's initrd with
 * the appended archive (live file system and session data) and the oneshot command line, built
 * by `restow-agent oneshot-payload` with the agent's own ISO reader and archive writer. QEMU's
 * direct kernel boot hands the kernel exactly that; kexec itself is not part of this test.
 *
 *   node scripts/recovery-e2e/oneshot-boot.mjs --iso <iso> --agent <restow-agent> [--work-dir DIR]
 *
 * The recovery program is masked; a check from a read-only ISO 9660 carrier looks at what the
 * live system got: the session data in /run/restow-oneshot (0700, file 0600, same bytes), no
 * /restow left of the initramfs, the medium a folder and not a disk, no login prompt on the
 * serial console, no secret on the kernel command line. Needs KVM, qemu-system-x86_64,
 * qemu-img and xorriso.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assertKvm, createDisk, startMachine, waitForSerial } from "./lib/qemu.mjs";

export const CARRIER_LABEL = "RESTOWCHECK";
/** A session secret made for this test only; it must not show up on the command line. */
export const TEST_SECRET = "5e".repeat(32);

/** The session data of the test (restow-oneshot-v1, valid for recover). */
export function sessionData() {
  return `${JSON.stringify({
    format: "restow-oneshot-v1",
    instanceUrl: "https://restow.invalid",
    lang: "en",
    session: { id: "oneshot-boot-test", secret: TEST_SECRET },
    confirmErase: ["serial.restow-oneshot-disk0"],
    consoles: ["ttyS0,115200n8"],
  })}\n`;
}

/** The command line: the one the agent printed, the recovery program kept away, the check run. */
export function cmdline(agentCmdline) {
  if (!agentCmdline.includes("restow.oneshot=1")) {
    throw new Error(`the agent's command line lacks restow.oneshot=1: ${agentCmdline}`);
  }
  return [
    agentCmdline.trim(),
    "systemd.mask=restow-recover.service",
    `systemd.run="/usr/bin/sh -c 'mkdir -p /run/restow-check && mount -o ro /dev/disk/by-label/${CARRIER_LABEL} /run/restow-check && exec sh /run/restow-check/run.sh'"`,
    "systemd.run_success_action=poweroff",
    "systemd.run_failure_action=poweroff",
  ].join(" ");
}

/** run.sh on the carrier: every check prints PASS or FAIL, the last line counts the failures. */
export function runScript(dataSha256) {
  if (!/^[0-9a-f]{64}$/.test(dataSha256)) throw new Error("dataSha256");
  return `#!/bin/sh
# Generated by scripts/recovery-e2e/oneshot-boot.mjs.
exec >/dev/ttyS0 2>&1
failed=0
check() {
  if [ "$2" = "$3" ]; then echo "PASS: $1"; else echo "FAIL: $1: '$2', want '$3'"; failed=$((failed + 1)); fi
}
d=/run/restow-oneshot
check "folder of the session data" "$(stat -c '%a %u' "$d" 2>&1)" "700 0"
check "session data" "$(stat -c '%a %u %F' "$d/oneshot.json" 2>&1)" "600 0 regular file"
check "the same bytes" "$(sha256sum <"$d/oneshot.json" | cut -c1-64)" "${dataSha256}"
check "nothing left of the initramfs" "$(test -e /restow && echo present || echo gone)" "gone"
check "the medium is a folder" "$(findmnt -n -o SOURCE /run/live/medium)" "rootfs[/restow/medium]"
check "the live file system" "$(findmnt -n -o FSTYPE /run/live/rootfs/filesystem.squashfs)" "squashfs"
check "no login prompt on ttyS0" "$(systemctl is-active serial-getty@ttyS0.service)" "inactive"
check "restow.oneshot=1" "$(grep -c 'restow.oneshot=1' /proc/cmdline)" "1"
check "no secret on the command line" "$(grep -c '${TEST_SECRET}' /proc/cmdline)" "0"
echo "ONESHOT-BOOT-MEMORY $(free -m | awk '/^Mem:/ { print "used=" $3 " shared=" $5 " total=" $2 }')"
echo "ONESHOT-BOOT-RESULT $failed"
`;
}

/** The number of failed checks from the serial log, or null without a result line. */
export function resultOf(serial) {
  const match = /ONESHOT-BOOT-RESULT (\d+)/.exec(serial);
  return match ? Number(match[1]) : null;
}

function parseArgs(argv) {
  const options = { workDir: "oneshot-boot-out" };
  for (let index = 0; index < argv.length; index++) {
    const flag = argv[index];
    const next = argv[index + 1];
    if (
      ["--iso", "--agent", "--work-dir"].includes(flag) &&
      (next === undefined || next.startsWith("--"))
    )
      throw new Error(`${flag} needs a value`);
    if (flag === "--iso") options.iso = argv[++index];
    else if (flag === "--agent") options.agent = argv[++index];
    else if (flag === "--work-dir") options.workDir = argv[++index];
    else throw new Error(`unknown option ${flag}`);
  }
  if (!options.iso || !options.agent)
    throw new Error("--iso <file> and --agent <restow-agent> are needed");
  return options;
}

function sh(command, args) {
  return execFileSync(command, args, { stdio: ["ignore", "pipe", "inherit"] }).toString("utf8");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  assertKvm();
  const workDir = resolve(options.workDir);
  mkdirSync(workDir, { recursive: true });
  const data = sessionData();
  const dataFile = join(workDir, "oneshot.json");
  writeFileSync(dataFile, data, { mode: 0o600 });
  const kernel = join(workDir, "vmlinuz");
  const initrd = join(workDir, "initrd-oneshot.img");
  const agentCmdline = sh(resolve(options.agent), [
    "oneshot-payload",
    "--iso",
    resolve(options.iso),
    "--data",
    dataFile,
    "--kernel-out",
    kernel,
    "--initrd-out",
    initrd,
    "--consoles",
    "ttyS0,115200n8",
  ]);
  const tree = join(workDir, "carrier");
  mkdirSync(tree, { recursive: true });
  writeFileSync(join(tree, "run.sh"), runScript(createHash("sha256").update(data).digest("hex")));
  const carrier = join(workDir, "carrier.iso");
  sh("xorriso", ["-as", "mkisofs", "-quiet", "-R", "-V", CARRIER_LABEL, "-o", carrier, tree]);
  const disk = {
    serial: "restow-oneshot-disk0",
    bus: "virtio",
    file: join(workDir, "disk0.qcow2"),
  };
  await createDisk((command, args) => sh(command, args), disk.file, "1G");
  const serialLog = join(workDir, "serial.log");
  const machine = startMachine({
    name: "oneshot-boot",
    firmware: "bios",
    memoryMiB: 2048,
    disks: [disk],
    extraDisks: [carrier],
    serialLog,
    qmpSocket: join(workDir, "qmp.sock"),
    kernel: { file: kernel, initrd, append: cmdline(agentCmdline) },
  });
  try {
    await waitForSerial(serialLog, /ONESHOT-BOOT-RESULT \d+/, {
      timeoutMs: 15 * 60_000,
      intervalMs: 1000,
      machine,
    });
  } finally {
    const timer = setTimeout(() => machine.child.kill("SIGKILL"), 120_000);
    await machine.exited;
    clearTimeout(timer);
  }
  const serial = readFileSync(serialLog, "utf8");
  const failed = resultOf(serial);
  for (const line of serial.split("\n")) {
    if (/^(PASS|FAIL): |^ONESHOT-BOOT-MEMORY /.test(line)) console.log(line.trimEnd());
  }
  if (failed !== 0) throw new Error(`oneshot-boot: ${failed ?? "no result"} check(s) failed`);
  console.log("oneshot-boot: the live system started without medium and got the session data");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
