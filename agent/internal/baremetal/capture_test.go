const captureDir = "testdata/capture"

var captureNow = func() time.Time { return time.Date(2026, 11, 4, 21, 0, 3, 0, time.UTC) }

func captureOptions(r cmdrun.Runner, root, host string) Options {
	return Options{Runner: r, Host: DirHost{Root: root}, Hostname: host, AgentVersion: "0.5.0", Hooks: "off", Now: captureNow, Arch: "amd64"}
}

// regenerateCaptureFixtures writes root/, cmd/, meta.json and expected.json
// for each simulated system.
func regenerateCaptureFixtures(t *testing.T) {
	t.Helper()
	for _, s := range simSystems() {
		dir := filepath.Join(captureDir, s.Name)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := s.writeTree(dir); err != nil {
			t.Fatalf("%s: %v", s.Name, err)
		}
		rec := newRecorder(s)
		m, _, err := Capture(context.Background(), captureOptions(rec, filepath.Join(dir, "root"), s.Hostname))
		if err != nil {
			t.Fatalf("%s: %v", s.Name, err)
		}
		if err := rec.write(dir); err != nil {
			t.Fatal(err)
		}
		b, err := m.Encode()
		if err != nil {
			t.Fatalf("%s: encode: %v", s.Name, err)
		}
		if err := os.WriteFile(filepath.Join(dir, "expected.json"), append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		meta, _ := json.MarshalIndent(map[string]any{"synthetic": true, "source": s.Source,
			"note": "Generated by the capture tests (sim_test.go) in the documented formats of the tools; to be replaced by a recording of a real machine (docs/BAREMETAL.md 27.1, 21.4 item 1)."}, "", "  ")
		if err := os.WriteFile(filepath.Join(dir, "meta.json"), append(meta, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// replay captures a fixture from its recordings.
func replay(t *testing.T, name string) (*Manifest, RawSet, *cmdrun.FakeRunner) {
	t.Helper()
	dir := filepath.Join(captureDir, name)
	f, err := cmdrun.LoadDir(t, filepath.Join(dir, "cmd"))
	if err != nil {
		t.Fatal(err)
	}
	var meta struct {
		Synthetic bool   `json:"synthetic"`
		Source    string `json:"source"`
	}
	b, err := os.ReadFile(filepath.Join(dir, "meta.json"))
	if err != nil || json.Unmarshal(b, &meta) != nil || meta.Source == "" {
		t.Fatalf("%s: meta.json: %v", name, err)
	}
	host := ""
	for _, s := range simSystems() {
		if s.Name == name {
			host = s.Hostname
		}
	}
	m, raw, err := Capture(context.Background(), captureOptions(f, filepath.Join(dir, "root"), host))
	if err != nil {
		t.Fatalf("%s: %v", name, err)
	}
	return m, raw, f
}

func TestCapture(t *testing.T) {
	if *update {
		regenerateCaptureFixtures(t)
	}
	dirs, _ := filepath.Glob(filepath.Join(captureDir, "*", "expected.json"))
	if len(dirs) < 25 {
		t.Fatalf("%d capture fixtures (run with -update)", len(dirs))
	}
	for _, p := range dirs {
		name := filepath.Base(filepath.Dir(p))
		t.Run(name, func(t *testing.T) {
			m, raw, f := replay(t, name)
			got, err := m.Encode()
			if err != nil {
				t.Fatal(err)
			}
			want, _ := os.ReadFile(p)
			if !bytes.Equal(got, bytes.TrimRight(want, "\n")) {
				t.Fatalf("capture differs from expected.json (run with -update and review the diff):\n%s", got)
			}
			if u := f.Unused(); len(u) > 0 {
				t.Errorf("recordings not used: %v", u)
			}
			for _, r := range m.Linux.Raw {
				if sha256Hex(raw[r.Name]) != r.SHA256 {
					t.Errorf("raw %s: hash mismatch", r.Name)
				}
			}
			// Every call was replayed from a recording; none may read keys.
			for _, c := range f.Calls() {
				if err := cmdrun.Forbidden(c); err != nil {
					t.Errorf("%q: %v", c, err)
				}
			}
		})
	}
}

// TestCaptureFindings checks the assessment of selected fixtures.
func TestCaptureFindings(t *testing.T) {
	cases := map[string]struct {
		verdict string
		codes   []string
	}{
		"ubuntu-zfs":                  {VerdictUnsupported, []string{CodeFSTypeUnsupported}},
		"container":                   {VerdictUnsupported, []string{CodeContainer}},
		"pve-raw-lvs":                 {VerdictSupportedWithWarnings, []string{CodePVEGuestVolumes}},
		"raid1-degraded":              {VerdictSupportedWithWarnings, []string{CodeMDDegraded, CodeBIOSNeedsCSM}},
		"dual-boot-windows":           {VerdictSupportedWithWarnings, []string{CodeDualBootWindows}},
		"docker-btrfs-many":           {VerdictSupportedWithWarnings, []string{CodeDockerBtrfsMany}},
		"opensuse-snapper-root-quota": {VerdictSupportedWithWarnings, []string{CodeSnapshotSubvolumes, CodeBIOSNeedsCSM}},
		"luks2-tpm2-clevis":           {VerdictSupportedWithWarnings, []string{CodeLUKSToken}},
		"alma9-xfs-lvm-devices":       {VerdictSupportedWithWarnings, []string{CodeLVMDeviceIDs}},
		"debian12-uefi-luks-lvm":      {VerdictSupported, nil},
	}
	for name, want := range cases {
		t.Run(name, func(t *testing.T) {
			b, err := os.ReadFile(filepath.Join(captureDir, name, "expected.json"))
			if err != nil {
				t.Fatal(err)
			}
			m, err := Decode(bytes.TrimRight(b, "\n"))
			if err != nil {
				t.Fatal(err)
			}
			if m.Linux.Verdict != want.verdict {
				t.Errorf("verdict %s, want %s: %+v", m.Linux.Verdict, want.verdict, m.Linux.Unsupported)
			}
			for _, c := range want.codes {
				if !hasCode(m.Linux.Unsupported, c) {
					t.Errorf("missing %s: %+v", c, m.Linux.Unsupported)
				}
			}
		})
	}
}

