// TestLUKSNoSecrets: neither the manifest nor raw/ carries digests, salts,
// keyslot areas or token contents (docs/BAREMETAL.md 4.2, 4.3).
func TestLUKSNoSecrets(t *testing.T) {
	for _, name := range []string{"luks2-tpm2-clevis", "debian12-uefi-luks-lvm", "luks1-encrypted-boot"} {
		m, raw, _ := replay(t, name)
		b, err := m.Encode()
		if err != nil {
			t.Fatal(err)
		}
		all := [][]byte{b}
		for _, v := range raw {
			all = append(all, v)
		}
		for _, chunk := range all {
			for _, s := range luks2Secrets {
				if bytes.Contains(chunk, []byte(s)) {
					t.Errorf("%s: %q leaked:\n%s", name, s, chunk)
				}
			}
			for _, s := range []string{`"salt"`, `"digest"`, `"area"`, `"af"`, "\"tokens\""} {
				if bytes.Contains(chunk, []byte(s)) {
					t.Errorf("%s: %s leaked", name, s)
				}
			}
		}
		var luksRaw int
		for n := range raw {
			if strings.HasPrefix(n, "luks-") {
				luksRaw++
			}
		}
		if luksRaw != len(m.Linux.LUKS) || luksRaw == 0 {
			t.Errorf("%s: %d raw luks files for %d volumes", name, luksRaw, len(m.Linux.LUKS))
		}
	}
	m, _, _ := replay(t, "luks2-tpm2-clevis")
	if got := strings.Join(m.Linux.LUKS[0].TokenTypes, ","); got != "clevis,systemd-tpm2" || m.Linux.LUKS[0].Keyslots != 3 {
		t.Fatalf("token types %q, keyslots %d", got, m.Linux.LUKS[0].Keyslots)
	}
}

// TestEFIAllowList: only the allow-listed variables are read.
func TestEFIAllowList(t *testing.T) {
	_, raw, _ := replay(t, "debian12-uefi-luks-lvm")
	if bytes.Contains(raw["efivars.json"], []byte("MokPWStore")) || bytes.Contains(raw["efivars.json"], []byte("PlatformLang")) {
		t.Fatalf("efivars.json holds a variable outside the allow-list")
	}
	for _, name := range []string{"MokPWStore", "PlatformLang"} {
		if efivarAllowed(name + "-" + EFIGlobalGUID) {
			t.Fatal(name)
		}
	}
}
